-- ============================================================================
-- ATS — V005: ticket comments and attachments
-- Comments are shared with everyone who can see the ticket (no private comments).
-- Deleting a comment or attachment is soft: the row stays, DELETED_AT/DELETED_BY say who and when.
-- Attachment bytes live on the filesystem (ats.attachments.dir); STORAGE_KEY is the relative path.
-- ============================================================================

CREATE SEQUENCE ATS_TICKET_COMMENTS_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE ATS_TICKET_COMMENTS (
  ID          NUMBER(19)   NOT NULL,
  TICKET_ID   NUMBER(19)   NOT NULL,
  AUTHOR_ID   NUMBER(19)   NOT NULL,
  BODY        NCLOB        NOT NULL,
  CREATED_AT  TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
  EDITED_AT   TIMESTAMP,
  DELETED_AT  TIMESTAMP,
  DELETED_BY  NUMBER(19),
  VERSION     NUMBER(10)   DEFAULT 0 NOT NULL,
  CONSTRAINT ATS_TICKET_COMMENTS_PK PRIMARY KEY (ID),
  CONSTRAINT ATS_TICKET_COMMENTS_TICKET_FK FOREIGN KEY (TICKET_ID) REFERENCES ATS_TICKETS (ID),
  CONSTRAINT ATS_TICKET_COMMENTS_AUTHOR_FK FOREIGN KEY (AUTHOR_ID) REFERENCES ATS_USERS (ID),
  CONSTRAINT ATS_TICKET_COMMENTS_DELBY_FK FOREIGN KEY (DELETED_BY) REFERENCES ATS_USERS (ID)
);

CREATE INDEX ATS_TICKET_COMMENTS_TICKET_IX ON ATS_TICKET_COMMENTS (TICKET_ID, CREATED_AT);

CREATE SEQUENCE ATS_ATTACHMENTS_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

-- PURPOSE: GENERAL (on the ticket), COMMENT (sent with a comment), EVIDENCE (test evidence).
CREATE TABLE ATS_ATTACHMENTS (
  ID            NUMBER(19)      NOT NULL,
  TICKET_ID     NUMBER(19)      NOT NULL,
  COMMENT_ID    NUMBER(19),
  PURPOSE       VARCHAR2(10)    DEFAULT 'GENERAL' NOT NULL,
  FILE_NAME     NVARCHAR2(255)  NOT NULL,
  CONTENT_TYPE  VARCHAR2(100)   NOT NULL,
  SIZE_BYTES    NUMBER(19)      NOT NULL,
  SHA256        VARCHAR2(64)    NOT NULL,
  STORAGE_KEY   VARCHAR2(200)   NOT NULL,
  UPLOADED_BY   NUMBER(19)      NOT NULL,
  UPLOADED_AT   TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
  DELETED_AT    TIMESTAMP,
  DELETED_BY    NUMBER(19),
  CONSTRAINT ATS_ATTACHMENTS_PK PRIMARY KEY (ID),
  CONSTRAINT ATS_ATTACHMENTS_PURPOSE_CK CHECK (PURPOSE IN ('GENERAL', 'COMMENT', 'EVIDENCE')),
  CONSTRAINT ATS_ATTACHMENTS_TICKET_FK FOREIGN KEY (TICKET_ID) REFERENCES ATS_TICKETS (ID),
  CONSTRAINT ATS_ATTACHMENTS_COMMENT_FK FOREIGN KEY (COMMENT_ID) REFERENCES ATS_TICKET_COMMENTS (ID),
  CONSTRAINT ATS_ATTACHMENTS_UPLOADER_FK FOREIGN KEY (UPLOADED_BY) REFERENCES ATS_USERS (ID),
  CONSTRAINT ATS_ATTACHMENTS_DELBY_FK FOREIGN KEY (DELETED_BY) REFERENCES ATS_USERS (ID)
);

CREATE INDEX ATS_ATTACHMENTS_TICKET_IX ON ATS_ATTACHMENTS (TICKET_ID);
CREATE INDEX ATS_ATTACHMENTS_COMMENT_IX ON ATS_ATTACHMENTS (COMMENT_ID);
