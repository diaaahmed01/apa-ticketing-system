-- ============================================================================
-- ATS — V003: tickets, people on tickets, ticket links, activity log
-- The ticket ID *is* the public number: TKT-1001, TKT-1002, ...
-- Tickets are never deleted (no DELETE path exists in the application).
-- ============================================================================

CREATE SEQUENCE ATS_TICKETS_SEQ START WITH 1001 INCREMENT BY 1 NOCACHE;

CREATE TABLE ATS_TICKETS (
  ID                    NUMBER(19)       NOT NULL,
  TITLE                 NVARCHAR2(200)   NOT NULL,
  DESCRIPTION           NCLOB            NOT NULL,
  TICKET_TYPE           VARCHAR2(20)     NOT NULL,
  PRIORITY              VARCHAR2(10)     NOT NULL,
  MODULE_ID             NUMBER(19)       NOT NULL,
  ENVIRONMENT           VARCHAR2(12)     NOT NULL,
  STATUS                VARCHAR2(30)     DEFAULT 'OPEN' NOT NULL,
  STATUS_BEFORE_BLOCK   VARCHAR2(30),
  CLOSURE_STATUS        VARCHAR2(12),
  CLOSURE_REASON        NVARCHAR2(2000),
  CLOSED_BY             NUMBER(19),
  CLOSED_AT             TIMESTAMP,
  ASSIGNEE_ID           NUMBER(19),
  ASSIGNED_BY           NUMBER(19),
  ASSIGNED_AT           TIMESTAMP,
  REVIEWER_ID           NUMBER(19),
  TESTER_ID             NUMBER(19),
  PATCH_REFERENCE       VARCHAR2(100),
  CREATED_BY            NUMBER(19)       NOT NULL,
  CREATED_AT            TIMESTAMP        DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT            TIMESTAMP,
  UPDATED_BY            NUMBER(19),
  VERSION               NUMBER(10)       DEFAULT 0 NOT NULL,
  CONSTRAINT ATS_TICKETS_PK PRIMARY KEY (ID),
  CONSTRAINT ATS_TICKETS_TYPE_CK CHECK (TICKET_TYPE IN ('BUG', 'CHANGE_REQUEST')),
  CONSTRAINT ATS_TICKETS_PRIO_CK CHECK (PRIORITY IN ('CRITICAL', 'HIGH', 'MEDIUM', 'LOW')),
  CONSTRAINT ATS_TICKETS_ENV_CK CHECK (ENVIRONMENT IN ('PRODUCTION', 'TESTING')),
  CONSTRAINT ATS_TICKETS_STATUS_CK CHECK (STATUS IN ('OPEN', 'IN_PROGRESS', 'CODE_REVIEW', 'TESTING',
    'READY_FOR_DEPLOYMENT', 'DEPLOYED', 'PRODUCTION_VERIFICATION', 'CLOSED', 'BLOCKED')),
  CONSTRAINT ATS_TICKETS_CLOSURE_CK CHECK (CLOSURE_STATUS IN ('RESOLVED', 'UNRESOLVED', 'CANCELLED')),
  CONSTRAINT ATS_TICKETS_CLOSED_CK CHECK ((STATUS = 'CLOSED' AND CLOSURE_STATUS IS NOT NULL) OR (STATUS <> 'CLOSED' AND CLOSURE_STATUS IS NULL)),
  CONSTRAINT ATS_TICKETS_MODULE_FK FOREIGN KEY (MODULE_ID) REFERENCES ATS_MODULES (ID),
  CONSTRAINT ATS_TICKETS_CREATOR_FK FOREIGN KEY (CREATED_BY) REFERENCES ATS_USERS (ID),
  CONSTRAINT ATS_TICKETS_ASSIGNEE_FK FOREIGN KEY (ASSIGNEE_ID) REFERENCES ATS_USERS (ID),
  CONSTRAINT ATS_TICKETS_REVIEWER_FK FOREIGN KEY (REVIEWER_ID) REFERENCES ATS_USERS (ID),
  CONSTRAINT ATS_TICKETS_TESTER_FK FOREIGN KEY (TESTER_ID) REFERENCES ATS_USERS (ID)
);

CREATE INDEX ATS_TICKETS_STATUS_IX ON ATS_TICKETS (STATUS);
CREATE INDEX ATS_TICKETS_ASSIGNEE_IX ON ATS_TICKETS (ASSIGNEE_ID);
CREATE INDEX ATS_TICKETS_CREATED_IX ON ATS_TICKETS (CREATED_AT);
CREATE INDEX ATS_TICKETS_MODULE_IX ON ATS_TICKETS (MODULE_ID);
CREATE INDEX ATS_TICKETS_CREATOR_IX ON ATS_TICKETS (CREATED_BY);

-- Collaborators and code contributors (one table, KIND tells them apart).
CREATE TABLE ATS_TICKET_PEOPLE (
  TICKET_ID   NUMBER(19)    NOT NULL,
  USER_ID     NUMBER(19)    NOT NULL,
  KIND        VARCHAR2(12)  NOT NULL,
  ADDED_AT    TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  ADDED_BY    NUMBER(19),
  CONSTRAINT ATS_TICKET_PEOPLE_PK PRIMARY KEY (TICKET_ID, USER_ID, KIND),
  CONSTRAINT ATS_TICKET_PEOPLE_KIND_CK CHECK (KIND IN ('COLLABORATOR', 'CONTRIBUTOR')),
  CONSTRAINT ATS_TICKET_PEOPLE_TICKET_FK FOREIGN KEY (TICKET_ID) REFERENCES ATS_TICKETS (ID),
  CONSTRAINT ATS_TICKET_PEOPLE_USER_FK FOREIGN KEY (USER_ID) REFERENCES ATS_USERS (ID)
);

CREATE INDEX ATS_TICKET_PEOPLE_USER_IX ON ATS_TICKET_PEOPLE (USER_ID);

-- Directed links. FOLLOW_UP_OF: FROM was raised because TO failed production verification.
CREATE TABLE ATS_TICKET_LINKS (
  FROM_TICKET_ID  NUMBER(19)    NOT NULL,
  TO_TICKET_ID    NUMBER(19)    NOT NULL,
  LINK_TYPE       VARCHAR2(20)  NOT NULL,
  CREATED_AT      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CREATED_BY      NUMBER(19),
  CONSTRAINT ATS_TICKET_LINKS_PK PRIMARY KEY (FROM_TICKET_ID, TO_TICKET_ID, LINK_TYPE),
  CONSTRAINT ATS_TICKET_LINKS_TYPE_CK CHECK (LINK_TYPE IN ('RELATED', 'FOLLOW_UP_OF', 'BLOCKED_BY')),
  CONSTRAINT ATS_TICKET_LINKS_SELF_CK CHECK (FROM_TICKET_ID <> TO_TICKET_ID),
  CONSTRAINT ATS_TICKET_LINKS_FROM_FK FOREIGN KEY (FROM_TICKET_ID) REFERENCES ATS_TICKETS (ID),
  CONSTRAINT ATS_TICKET_LINKS_TO_FK FOREIGN KEY (TO_TICKET_ID) REFERENCES ATS_TICKETS (ID)
);

CREATE INDEX ATS_TICKET_LINKS_TO_IX ON ATS_TICKET_LINKS (TO_TICKET_ID);

-- Append-only history shown as the Activity timeline.
CREATE SEQUENCE ATS_TICKET_ACTIVITY_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE ATS_TICKET_ACTIVITY (
  ID          NUMBER(19)      NOT NULL,
  TICKET_ID   NUMBER(19)      NOT NULL,
  ACTOR_ID    NUMBER(19)      NOT NULL,
  ACTION      VARCHAR2(40)    NOT NULL,
  FIELD       VARCHAR2(40),
  OLD_VALUE   NVARCHAR2(400),
  NEW_VALUE   NVARCHAR2(400),
  NOTE        NVARCHAR2(2000),
  CREATED_AT  TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT ATS_TICKET_ACTIVITY_PK PRIMARY KEY (ID),
  CONSTRAINT ATS_TICKET_ACTIVITY_TICKET_FK FOREIGN KEY (TICKET_ID) REFERENCES ATS_TICKETS (ID),
  CONSTRAINT ATS_TICKET_ACTIVITY_ACTOR_FK FOREIGN KEY (ACTOR_ID) REFERENCES ATS_USERS (ID)
);

CREATE INDEX ATS_TICKET_ACTIVITY_TICKET_IX ON ATS_TICKET_ACTIVITY (TICKET_ID, CREATED_AT);
