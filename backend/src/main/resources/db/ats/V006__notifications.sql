-- ============================================================================
-- ATS — V006: in-app notifications and the email outbox
-- A notification row is written in the same transaction as the ticket change that caused it.
-- ATS_EMAIL_OUTBOX holds one PENDING row per notification whose recipient has an email address;
-- the mail job (ats.mail.enabled) sends them later, so nothing is lost while sending is off.
-- ============================================================================

CREATE SEQUENCE ATS_NOTIFICATIONS_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE ATS_NOTIFICATIONS (
  ID          NUMBER(19)       NOT NULL,
  USER_ID     NUMBER(19)       NOT NULL,
  TICKET_ID   NUMBER(19),
  TYPE        VARCHAR2(40)     NOT NULL,
  ACTOR_ID    NUMBER(19),
  TITLE       NVARCHAR2(300)   NOT NULL,
  BODY        NVARCHAR2(1000),
  CREATED_AT  TIMESTAMP        DEFAULT SYSTIMESTAMP NOT NULL,
  READ_AT     TIMESTAMP,
  CONSTRAINT ATS_NOTIFICATIONS_PK PRIMARY KEY (ID),
  CONSTRAINT ATS_NOTIFICATIONS_USER_FK FOREIGN KEY (USER_ID) REFERENCES ATS_USERS (ID),
  CONSTRAINT ATS_NOTIFICATIONS_TICKET_FK FOREIGN KEY (TICKET_ID) REFERENCES ATS_TICKETS (ID),
  CONSTRAINT ATS_NOTIFICATIONS_ACTOR_FK FOREIGN KEY (ACTOR_ID) REFERENCES ATS_USERS (ID)
);

CREATE INDEX ATS_NOTIFICATIONS_USER_IX ON ATS_NOTIFICATIONS (USER_ID, READ_AT, CREATED_AT);

CREATE SEQUENCE ATS_EMAIL_OUTBOX_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE ATS_EMAIL_OUTBOX (
  ID               NUMBER(19)       NOT NULL,
  TO_ADDRESS       VARCHAR2(320)    NOT NULL,
  SUBJECT          NVARCHAR2(300)   NOT NULL,
  BODY_TEXT        NCLOB            NOT NULL,
  NOTIFICATION_ID  NUMBER(19),
  STATUS           VARCHAR2(10)     DEFAULT 'PENDING' NOT NULL,
  ATTEMPTS         NUMBER(3)        DEFAULT 0 NOT NULL,
  LAST_ERROR       NVARCHAR2(1000),
  CREATED_AT       TIMESTAMP        DEFAULT SYSTIMESTAMP NOT NULL,
  SENT_AT          TIMESTAMP,
  CONSTRAINT ATS_EMAIL_OUTBOX_PK PRIMARY KEY (ID),
  CONSTRAINT ATS_EMAIL_OUTBOX_STATUS_CK CHECK (STATUS IN ('PENDING', 'SENT', 'FAILED', 'SKIPPED')),
  CONSTRAINT ATS_EMAIL_OUTBOX_NOTIF_FK FOREIGN KEY (NOTIFICATION_ID) REFERENCES ATS_NOTIFICATIONS (ID)
);

CREATE INDEX ATS_EMAIL_OUTBOX_STATUS_IX ON ATS_EMAIL_OUTBOX (STATUS, CREATED_AT);
